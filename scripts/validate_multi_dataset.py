#!/usr/bin/env python3
"""Validate the reproducibility and ground truth of a V4 multi-Trojan dataset.

The canonical case schema is ``v4-multi-independent-trojan/1`` and the
canonical ground-truth schema is ``v4-groundtruth-1``.  The loader also
accepts a top-level ``cases`` array, JSONL manifests, and a few legacy field
aliases so that an aggregate manifest can be assembled without rewriting each
case manifest.

This script deliberately uses only the Python standard library.  It is safe to
run before ground truth has been generated by passing
``--allow-missing-groundtruth``; a release/final validation should not use that
option.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections import Counter, defaultdict
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable, Iterator, Mapping, Sequence


CASE_SCHEMA = "v4-multi-independent-trojan/1"
GT_SCHEMA = "v4-groundtruth-1"
NEGATIVE_SCHEMA = "v4-hard-negatives-1"
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
BITS_RE = re.compile(r"^[01]+$")
BENCH_DECL_RE = re.compile(r"^\s*(INPUT|OUTPUT)\s*\(\s*([^()]+?)\s*\)", re.I)


@dataclass
class Issue:
    severity: str
    code: str
    message: str
    case_id: str | None = None
    path: str | None = None


@dataclass
class CaseRecord:
    data: dict[str, Any]
    source: Path
    base_dir: Path
    index_data: dict[str, Any] | None = None


@dataclass(frozen=True)
class GroundtruthProfileRule:
    profile_id: str
    witnesses_per_mask: int
    hard_negatives: int
    witnesses_per_singleton: int | None = None
    witnesses_per_pair: int | None = None
    witnesses_per_all: int | None = None


@dataclass
class ValidationState:
    strict: bool = False
    issues: list[Issue] = field(default_factory=list)
    counters: Counter[str] = field(default_factory=Counter)
    by_benchmark: dict[str, Counter[str]] = field(
        default_factory=lambda: defaultdict(Counter)
    )
    case_rows: list[dict[str, Any]] = field(default_factory=list)

    def issue(
        self,
        severity: str,
        code: str,
        message: str,
        *,
        case_id: str | None = None,
        path: Path | str | None = None,
        strict_error: bool = False,
    ) -> None:
        if severity == "WARNING" and strict_error and self.strict:
            severity = "ERROR"
        self.issues.append(
            Issue(
                severity=severity,
                code=code,
                message=message,
                case_id=case_id,
                path=str(path) if path is not None else None,
            )
        )


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def parse_bench_interfaces(path: Path) -> tuple[list[str], list[str]]:
    primary_inputs: list[str] = []
    primary_outputs: list[str] = []
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            match = BENCH_DECL_RE.match(line)
            if not match:
                continue
            target = primary_inputs if match.group(1).upper() == "INPUT" else primary_outputs
            target.append(match.group(2).strip())
    return primary_inputs, primary_outputs


def count_bench_assignments(path: Path) -> int:
    count = 0
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            stripped = line.strip()
            if stripped and not stripped.startswith("#") and "=" in stripped:
                count += 1
    return count


def read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def records_from_json(path: Path, value: Any) -> list[CaseRecord]:
    if isinstance(value, list):
        cases = value
    elif isinstance(value, dict) and isinstance(value.get("cases"), list):
        cases = value["cases"]
    elif isinstance(value, dict):
        cases = [value]
    else:
        raise ValueError("manifest root must be an object, an array, or an object with cases[]")

    records: list[CaseRecord] = []
    for index, case in enumerate(cases):
        if not isinstance(case, dict):
            raise ValueError(f"case #{index} is not an object")
        case_manifest = case.get("case_manifest")
        if isinstance(case_manifest, str):
            relative = Path(case_manifest)
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError(
                    f"case #{index} has unsafe case_manifest path: {case_manifest}"
                )
            target = (path.parent / relative).resolve()
            loaded = read_json(target)
            if not isinstance(loaded, dict):
                raise ValueError(f"referenced case manifest is not an object: {target}")
            records.append(CaseRecord(loaded, target, target.parent, dict(case)))
        else:
            records.append(CaseRecord(case, path, path.parent))
    return records


def load_manifest(path: Path) -> list[CaseRecord]:
    if path.suffix.lower() == ".jsonl":
        records: list[CaseRecord] = []
        with path.open("r", encoding="utf-8") as handle:
            for line_number, line in enumerate(handle, 1):
                if not line.strip():
                    continue
                value = json.loads(line)
                if not isinstance(value, dict):
                    raise ValueError(f"JSONL line {line_number} is not an object")
                case_manifest = value.get("case_manifest")
                if isinstance(case_manifest, str):
                    relative = Path(case_manifest)
                    if relative.is_absolute() or ".." in relative.parts:
                        raise ValueError(
                            f"JSONL line {line_number} has unsafe case_manifest path"
                        )
                    target = (path.parent / relative).resolve()
                    loaded = read_json(target)
                    if not isinstance(loaded, dict):
                        raise ValueError(
                            f"JSONL line {line_number} references a non-object manifest"
                        )
                    records.append(CaseRecord(loaded, target, target.parent, dict(value)))
                else:
                    records.append(CaseRecord(value, path, path.parent))
        return records
    return records_from_json(path, read_json(path))


def discover_manifests(dataset_root: Path) -> list[Path]:
    aggregate_names = (
        "dataset_manifest.json",
        "dataset_manifest.jsonl",
        "manifest.json",
        "manifest.jsonl",
    )
    aggregate = [dataset_root / name for name in aggregate_names if (dataset_root / name).is_file()]
    if aggregate:
        return aggregate
    return sorted(dataset_root.rglob("case_manifest.json"))


def expand_manifest_arguments(paths: Sequence[Path]) -> list[Path]:
    expanded: list[Path] = []
    for path in paths:
        if path.is_dir():
            expanded.extend(discover_manifests(path))
        else:
            expanded.append(path)
    return sorted(set(item.resolve() for item in expanded))


def get_first(mapping: Mapping[str, Any], names: Sequence[str]) -> Any:
    for name in names:
        if name in mapping:
            return mapping[name]
    return None


def nested_get(mapping: Mapping[str, Any], *path: str) -> Any:
    value: Any = mapping
    for key in path:
        if not isinstance(value, Mapping) or key not in value:
            return None
        value = value[key]
    return value


def safe_case_path(
    raw: Any,
    record: CaseRecord,
    state: ValidationState,
    case_id: str,
    label: str,
) -> Path | None:
    if isinstance(raw, Mapping):
        raw = get_first(raw, ("relative_path", "path", "file"))
    if not isinstance(raw, str) or not raw.strip():
        state.issue("ERROR", "MISSING_PATH", f"missing {label} path", case_id=case_id)
        return None
    candidate = Path(raw)
    if candidate.is_absolute():
        state.issue(
            "ERROR",
            "ABSOLUTE_PATH",
            f"{label} must be relative to its manifest: {raw}",
            case_id=case_id,
            path=record.source,
        )
        return candidate
    if ".." in candidate.parts:
        state.issue(
            "ERROR",
            "PATH_TRAVERSAL",
            f"{label} contains '..': {raw}",
            case_id=case_id,
            path=record.source,
        )
    return (record.base_dir / candidate).resolve()


def normalize_relpath(value: str) -> str:
    return Path(value).as_posix().lstrip("./")


def infer_benchmark(record: CaseRecord, case: Mapping[str, Any]) -> str:
    explicit = get_first(case, ("benchmark", "circuit", "circuit_name"))
    if isinstance(explicit, str) and explicit:
        return explicit
    generated = nested_get(case, "generation", "benchmark")
    if isinstance(generated, str) and generated:
        return generated
    # Canonical layout: <dataset>/<benchmark>/<case_id>/case_manifest.json
    if record.source.name == "case_manifest.json" and len(record.source.parents) >= 2:
        return record.source.parent.parent.name
    case_id = str(get_first(case, ("case_id", "id", "name")) or "")
    return case_id.split("_", 1)[0] if "_" in case_id else "unknown"


def canonical_instances(case: Mapping[str, Any]) -> list[dict[str, Any]]:
    value = get_first(case, ("instances", "trojans", "trojan_instances"))
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def instance_id(instance: Mapping[str, Any]) -> str:
    value = get_first(instance, ("instance_id", "trojan_id", "id", "name"))
    return str(value) if value is not None else ""


def instance_victim(instance: Mapping[str, Any]) -> str:
    value = get_first(instance, ("victim_net", "victim", "payload_victim"))
    if value is None:
        value = nested_get(instance, "payload", "victim_net")
    if value is None:
        value = nested_get(instance, "payload", "source_net")
    return str(value) if value is not None else ""


def check_file_table(
    record: CaseRecord,
    case_id: str,
    expected_paths: Sequence[tuple[str, Any]],
    state: ValidationState,
    skip_hash: bool,
) -> dict[str, Path]:
    case = record.data
    files = case.get("files")
    if not isinstance(files, Mapping):
        state.issue("ERROR", "MISSING_FILE_TABLE", "manifest files{} is required", case_id=case_id)
        files = {}

    resolved_expected: dict[str, Path] = {}
    expected_relpaths: set[str] = set()
    for label, raw in expected_paths:
        path = safe_case_path(raw, record, state, case_id, label)
        if path is None:
            continue
        resolved_expected[label] = path
        if isinstance(raw, str) and not Path(raw).is_absolute():
            expected_relpaths.add(normalize_relpath(raw))

    normalized_files = {normalize_relpath(str(key)): value for key, value in files.items()}
    for relpath in sorted(expected_relpaths):
        if relpath not in normalized_files:
            state.issue(
                "ERROR",
                "UNHASHED_REFERENCED_FILE",
                f"referenced file is absent from files{{}}: {relpath}",
                case_id=case_id,
                path=record.source,
            )

    for relpath, metadata in normalized_files.items():
        path = safe_case_path(relpath, record, state, case_id, f"files[{relpath}]")
        if path is None:
            continue
        state.counters["files_declared"] += 1
        if not path.is_file():
            state.issue(
                "ERROR", "FILE_NOT_FOUND", f"declared file does not exist: {relpath}",
                case_id=case_id, path=path,
            )
            continue
        state.counters["files_present"] += 1
        if not isinstance(metadata, Mapping):
            state.issue(
                "ERROR", "BAD_FILE_METADATA", f"files[{relpath}] must be an object",
                case_id=case_id, path=record.source,
            )
            continue

        expected_size = metadata.get("size_bytes")
        actual_size = path.stat().st_size
        if not isinstance(expected_size, int):
            state.issue(
                "ERROR", "MISSING_FILE_SIZE", f"files[{relpath}].size_bytes is required",
                case_id=case_id, path=record.source,
            )
        elif expected_size != actual_size:
            state.issue(
                "ERROR", "FILE_SIZE_MISMATCH",
                f"{relpath}: expected {expected_size} bytes, got {actual_size}",
                case_id=case_id, path=path,
            )
        else:
            state.counters["sizes_verified"] += 1

        expected_hash = metadata.get("sha256")
        if not isinstance(expected_hash, str) or not SHA256_RE.fullmatch(expected_hash.lower()):
            state.issue(
                "ERROR", "BAD_SHA256", f"files[{relpath}].sha256 must be 64 hex characters",
                case_id=case_id, path=record.source,
            )
        elif not skip_hash:
            actual_hash = sha256_file(path)
            if actual_hash != expected_hash.lower():
                state.issue(
                    "ERROR", "SHA256_MISMATCH",
                    f"{relpath}: expected {expected_hash.lower()}, got {actual_hash}",
                    case_id=case_id, path=path,
                )
            else:
                state.counters["hashes_verified"] += 1
    return resolved_expected


def validate_interfaces(
    case: Mapping[str, Any],
    paths: Mapping[str, Path],
    state: ValidationState,
    case_id: str,
) -> tuple[list[str], list[str]]:
    interfaces = case.get("interfaces")
    if not isinstance(interfaces, Mapping):
        state.issue("ERROR", "MISSING_INTERFACES", "interfaces{} is required", case_id=case_id)
        return [], []
    primary_inputs = interfaces.get("primary_inputs")
    primary_outputs = interfaces.get("primary_outputs")
    if not isinstance(primary_inputs, list) or not all(isinstance(x, str) for x in primary_inputs):
        state.issue("ERROR", "BAD_PRIMARY_INPUTS", "interfaces.primary_inputs must be a string array", case_id=case_id)
        primary_inputs = []
    if not isinstance(primary_outputs, list) or not all(isinstance(x, str) for x in primary_outputs):
        state.issue("ERROR", "BAD_PRIMARY_OUTPUTS", "interfaces.primary_outputs must be a string array", case_id=case_id)
        primary_outputs = []
    if len(primary_inputs) != len(set(primary_inputs)):
        state.issue("ERROR", "DUPLICATE_PRIMARY_INPUT", "primary_inputs contains duplicate names", case_id=case_id)
    if len(primary_outputs) != len(set(primary_outputs)):
        state.issue("ERROR", "DUPLICATE_PRIMARY_OUTPUT", "primary_outputs contains duplicate names", case_id=case_id)

    for label in ("golden", "combined"):
        path = paths.get(label)
        if path is None or not path.is_file():
            continue
        parsed_inputs, parsed_outputs = parse_bench_interfaces(path)
        if parsed_inputs != primary_inputs:
            state.issue(
                "ERROR", "PI_INTERFACE_MISMATCH",
                f"{label} PI declarations differ from interfaces.primary_inputs",
                case_id=case_id, path=path,
            )
        if parsed_outputs != primary_outputs:
            state.issue(
                "ERROR", "PO_INTERFACE_MISMATCH",
                f"{label} PO declarations differ from interfaces.primary_outputs",
                case_id=case_id, path=path,
            )
    return list(primary_inputs), list(primary_outputs)


def validate_instances(
    case: Mapping[str, Any],
    instances: Sequence[Mapping[str, Any]],
    state: ValidationState,
    case_id: str,
) -> tuple[list[str], list[str]]:
    generation = case.get("generation") if isinstance(case.get("generation"), Mapping) else {}
    declared_count = generation.get("trojan_count")
    declared_trigger_size = generation.get("trigger_size")
    seed = generation.get("seed")
    if not isinstance(seed, int) or isinstance(seed, bool) or seed < 0:
        state.issue("ERROR", "BAD_GENERATION_SEED", "generation.seed must be a non-negative integer", case_id=case_id)
    if not isinstance(declared_trigger_size, int) or isinstance(declared_trigger_size, bool) or declared_trigger_size < 1:
        state.issue("ERROR", "BAD_TRIGGER_SIZE", "generation.trigger_size must be a positive integer", case_id=case_id)
    if not isinstance(declared_count, int) or declared_count < 1:
        state.issue("ERROR", "BAD_TROJAN_COUNT", "generation.trojan_count must be a positive integer", case_id=case_id)
    elif declared_count != len(instances):
        state.issue(
            "ERROR", "TROJAN_COUNT_MISMATCH",
            f"generation.trojan_count={declared_count}, but instances has {len(instances)} entries",
            case_id=case_id,
        )
    if not instances:
        state.issue("ERROR", "NO_INSTANCES", "at least one Trojan instance is required", case_id=case_id)

    ids = [instance_id(item) for item in instances]
    victims = [instance_victim(item) for item in instances]
    if any(not value for value in ids):
        state.issue("ERROR", "MISSING_INSTANCE_ID", "every instance needs instance_id", case_id=case_id)
    if len(ids) != len(set(ids)):
        state.issue("ERROR", "DUPLICATE_INSTANCE_ID", "instance_id values must be unique", case_id=case_id)
    if any(not value for value in victims):
        state.issue("ERROR", "MISSING_VICTIM", "every instance needs victim_net", case_id=case_id)
    if len(victims) != len(set(victims)):
        state.issue(
            "ERROR", "DUPLICATE_VICTIM",
            "independent multi-Trojan cases must use distinct victim nets",
            case_id=case_id,
        )

    for item, item_id in zip(instances, ids):
        trigger = item.get("trigger")
        literals = trigger.get("literals") if isinstance(trigger, Mapping) else None
        if not isinstance(literals, list) or not literals:
            state.issue("ERROR", "NO_TRIGGER_LITERALS", f"{item_id}: trigger.literals must be non-empty", case_id=case_id)
            continue
        if isinstance(declared_trigger_size, int) and len(literals) != declared_trigger_size:
            state.issue(
                "ERROR", "TRIGGER_SIZE_MISMATCH",
                f"{item_id}: trigger has {len(literals)} literals, generation.trigger_size={declared_trigger_size}",
                case_id=case_id,
            )
        literal_nets: list[str] = []
        for literal in literals:
            if not isinstance(literal, Mapping):
                state.issue("ERROR", "BAD_TRIGGER_LITERAL", f"{item_id}: trigger literal is not an object", case_id=case_id)
                continue
            net = literal.get("net")
            required = literal.get("required_value")
            if not isinstance(net, str) or not net:
                state.issue("ERROR", "BAD_TRIGGER_NET", f"{item_id}: trigger literal has no net", case_id=case_id)
            else:
                literal_nets.append(net)
            if required not in (0, 1):
                state.issue("ERROR", "BAD_REQUIRED_VALUE", f"{item_id}: required_value must be 0 or 1", case_id=case_id)
        if len(literal_nets) != len(set(literal_nets)):
            state.issue("ERROR", "DUPLICATE_TRIGGER_LITERAL", f"{item_id}: a trigger net appears more than once", case_id=case_id)
    return ids, victims


def validate_trigger_witnesses(
    case: Mapping[str, Any],
    instances: Sequence[Mapping[str, Any]],
    ids: Sequence[str],
    primary_inputs: Sequence[str],
    state: ValidationState,
    case_id: str,
) -> None:
    """Validate the generator's constructive witnesses for every exact mask.

    Mask characters are ordered exactly like instances[]: for [HT0, HT1],
    HT0's singleton is ``10``.  These witnesses prove trigger satisfiability;
    they do not replace the GT tool's separate PO-observability witnesses.
    """
    root = case.get("trigger_witnesses")
    if not isinstance(root, Mapping):
        state.issue(
            "ERROR", "MISSING_TRIGGER_WITNESSES",
            "trigger_witnesses{} is required for constructive exact-mask validation",
            case_id=case_id,
        )
        return
    assignments = root.get("partial_pi_assignments")
    if not isinstance(assignments, Mapping):
        state.issue(
            "ERROR", "BAD_TRIGGER_WITNESSES",
            "trigger_witnesses.partial_pi_assignments must be an object",
            case_id=case_id,
        )
        return
    width = len(instances)
    expected_masks = {format(value, f"0{width}b") for value in range(1 << width)}
    actual_masks = {str(mask) for mask in assignments}
    if actual_masks != expected_masks:
        missing = sorted(expected_masks - actual_masks)
        extra = sorted(actual_masks - expected_masks)
        state.issue(
            "ERROR", "TRIGGER_WITNESS_MASK_SET",
            f"exact-mask witnesses differ from all 2^N masks; missing={missing}, extra={extra}",
            case_id=case_id,
        )

    pi_set = set(primary_inputs)
    for mask in sorted(expected_masks & actual_masks):
        assignment = assignments.get(mask)
        if not isinstance(assignment, Mapping):
            state.issue(
                "ERROR", "BAD_TRIGGER_WITNESS_ASSIGNMENT",
                f"mask {mask} witness must be a PI-to-bit object",
                case_id=case_id,
            )
            continue
        bad_values = sorted(
            str(net) for net, value in assignment.items() if value not in (0, 1)
        )
        unknown_pis = sorted(str(net) for net in assignment if str(net) not in pi_set)
        if bad_values:
            state.issue(
                "ERROR", "BAD_TRIGGER_WITNESS_VALUE",
                f"mask {mask} has non-binary assignments for {bad_values}",
                case_id=case_id,
            )
        if unknown_pis:
            state.issue(
                "ERROR", "UNKNOWN_TRIGGER_WITNESS_PI",
                f"mask {mask} assigns nets that are not primary inputs: {unknown_pis}",
                case_id=case_id,
            )

        for position, instance in enumerate(instances):
            trigger = instance.get("trigger")
            literals = trigger.get("literals") if isinstance(trigger, Mapping) else []
            active = True
            for literal in literals if isinstance(literals, list) else []:
                if not isinstance(literal, Mapping):
                    active = False
                    continue
                net = literal.get("net")
                required = literal.get("required_value")
                if net not in assignment:
                    state.issue(
                        "ERROR", "INCOMPLETE_TRIGGER_WITNESS",
                        f"mask {mask} does not assign trigger PI {net!r} for {ids[position]}",
                        case_id=case_id,
                    )
                    active = False
                elif assignment.get(net) != required:
                    active = False
            expected_active = mask[position] == "1"
            if active != expected_active:
                state.issue(
                    "ERROR", "TRIGGER_WITNESS_SEMANTICS",
                    f"mask {mask} evaluates {ids[position]}={int(active)}, expected {int(expected_active)}",
                    case_id=case_id,
                )
        state.counters["trigger_witness_masks_verified"] += 1


def parse_mask(value: Any, width: int) -> str | None:
    if isinstance(value, str) and BITS_RE.fullmatch(value) and len(value) == width:
        return value
    if isinstance(value, int) and value >= 0 and value < (1 << width):
        return format(value, f"0{width}b")
    return None


def requested_groundtruth_masks(trojan_count: int) -> list[str]:
    """Return the canonical ``--mask-set auto`` masks in generator order."""
    if trojan_count < 1:
        return []

    def bits(value: int) -> str:
        return format(value, f"0{trojan_count}b")

    if trojan_count <= 3:
        return [bits(value) for value in range(1, 1 << trojan_count)]

    masks: list[int] = []
    seen: set[int] = set()

    def add(value: int) -> None:
        if value and value not in seen:
            seen.add(value)
            masks.append(value)

    for first in range(trojan_count):
        add(1 << (trojan_count - 1 - first))
    for first in range(trojan_count):
        for second in range(first + 1, trojan_count):
            add(
                (1 << (trojan_count - 1 - first))
                | (1 << (trojan_count - 1 - second))
            )
    add((1 << trojan_count) - 1)
    return [bits(value) for value in masks]


def groundtruth_witness_target(rule: GroundtruthProfileRule, mask: str) -> int:
    """Mirror generate_multi_gt's override precedence exactly."""
    active = mask.count("1")
    if active == 1 and rule.witnesses_per_singleton is not None:
        return rule.witnesses_per_singleton
    if active == len(mask) and rule.witnesses_per_all is not None:
        return rule.witnesses_per_all
    if active == 2 and rule.witnesses_per_pair is not None:
        return rule.witnesses_per_pair
    return rule.witnesses_per_mask


def find_groundtruth_candidate(record: CaseRecord) -> Path | None:
    case = record.data
    raw = get_first(case, ("groundtruth_path", "ground_truth_path", "gt_path", "patterns_path"))
    if isinstance(raw, str):
        return (record.base_dir / raw).resolve() if not Path(raw).is_absolute() else Path(raw)
    candidates: list[Path] = []
    for name in ("groundtruth.json", "ground_truth.json", "gt.json"):
        candidate = record.base_dir / name
        if candidate.is_file():
            candidates.append(candidate)
    candidates.extend(sorted(record.base_dir.glob("*_groundtruth.json")))
    return candidates[0].resolve() if candidates else None


def find_negative_candidate(record: CaseRecord) -> Path | None:
    raw = get_first(
        record.data,
        ("negative_patterns_path", "hard_negatives_path", "negative_path"),
    )
    if isinstance(raw, str):
        return (record.base_dir / raw).resolve() if not Path(raw).is_absolute() else Path(raw)
    candidates: list[Path] = []
    for name in ("negative_patterns.json", "hard_negatives.json"):
        candidate = record.base_dir / name
        if candidate.is_file():
            candidates.append(candidate)
    candidates.extend(sorted(record.base_dir.glob("*_negative_patterns.json")))
    return candidates[0].resolve() if candidates else None


def index_artifacts(
    root: Path, state: ValidationState
) -> tuple[
    dict[str, list[tuple[Path, dict[str, Any]]]],
    dict[str, list[tuple[Path, dict[str, Any]]]],
]:
    groundtruth_index: dict[str, list[tuple[Path, dict[str, Any]]]] = defaultdict(list)
    negative_index: dict[str, list[tuple[Path, dict[str, Any]]]] = defaultdict(list)
    if not root.is_dir():
        state.issue("ERROR", "GT_ROOT_NOT_FOUND", "ground-truth root does not exist", path=root)
        return groundtruth_index, negative_index
    for path in sorted(root.rglob("*.json")):
        if path.name == "case_manifest.json":
            continue
        try:
            value = read_json(path)
        except (OSError, json.JSONDecodeError) as error:
            state.issue("ERROR", "GT_JSON_PARSE", str(error), path=path)
            continue
        if not isinstance(value, dict) or not isinstance(value.get("patterns"), list):
            continue
        case_id = value.get("case_id")
        if isinstance(case_id, str) and case_id:
            if value.get("schema_version") == GT_SCHEMA:
                groundtruth_index[case_id].append((path.resolve(), value))
            elif value.get("schema_version") == NEGATIVE_SCHEMA:
                negative_index[case_id].append((path.resolve(), value))
    return groundtruth_index, negative_index


def validate_groundtruth(
    gt: Mapping[str, Any],
    gt_path: Path,
    case_manifest: Mapping[str, Any],
    case_id: str,
    benchmark: str,
    primary_inputs: Sequence[str],
    primary_outputs: Sequence[str],
    ids: Sequence[str],
    profile_rule: GroundtruthProfileRule | None,
    state: ValidationState,
) -> dict[str, int]:
    stats = Counter[str]()
    if gt.get("schema_version") != GT_SCHEMA:
        state.issue(
            "ERROR", "BAD_GT_SCHEMA",
            f"expected ground-truth schema {GT_SCHEMA!r}, got {gt.get('schema_version')!r}",
            case_id=case_id, path=gt_path,
        )
    if gt.get("case_id") != case_id:
        state.issue(
            "ERROR", "GT_CASE_ID_MISMATCH",
            f"ground truth case_id={gt.get('case_id')!r}, expected {case_id!r}",
            case_id=case_id, path=gt_path,
        )
    if gt.get("complete") is not True:
        state.issue(
            "ERROR", "INCOMPLETE_GROUNDTRUTH",
            "ground truth must set complete=true; unknown/timeout/unobservable requested masks are not release GT",
            case_id=case_id, path=gt_path,
        )

    golden_relative = get_first(
        case_manifest, ("golden_path", "golden_file", "golden")
    )
    combined_relative = get_first(
        case_manifest, ("combined_path", "trojaned_path", "trojan_file", "combined")
    )
    if gt.get("origin_path") != golden_relative:
        state.issue(
            "ERROR", "GT_ORIGIN_PATH_MISMATCH",
            f"ground truth origin_path={gt.get('origin_path')!r}, manifest={golden_relative!r}",
            case_id=case_id, path=gt_path,
        )
    if gt.get("trojan_path") != combined_relative:
        state.issue(
            "ERROR", "GT_TROJAN_PATH_MISMATCH",
            f"ground truth trojan_path={gt.get('trojan_path')!r}, manifest={combined_relative!r}",
            case_id=case_id, path=gt_path,
        )
    files = case_manifest.get("files")
    normalized_files = (
        {normalize_relpath(str(key)): value for key, value in files.items()}
        if isinstance(files, Mapping)
        else {}
    )
    for gt_hash_field, relative in (
        ("origin_sha256", golden_relative),
        ("trojan_sha256", combined_relative),
    ):
        manifest_hash = None
        if isinstance(relative, str):
            metadata = normalized_files.get(normalize_relpath(relative))
            if isinstance(metadata, Mapping):
                manifest_hash = metadata.get("sha256")
        if not isinstance(manifest_hash, str) or gt.get(gt_hash_field) != manifest_hash:
            state.issue(
                "ERROR", "GT_CIRCUIT_HASH_MISMATCH",
                f"ground truth {gt_hash_field}={gt.get(gt_hash_field)!r}, manifest={manifest_hash!r}",
                case_id=case_id, path=gt_path,
            )
    gt_benchmark = gt.get("benchmark")
    if isinstance(gt_benchmark, str) and benchmark != "unknown" and gt_benchmark != benchmark:
        state.issue(
            "ERROR", "GT_BENCHMARK_MISMATCH",
            f"ground truth benchmark={gt_benchmark!r}, expected {benchmark!r}",
            case_id=case_id, path=gt_path,
        )

    pi_order = gt.get("pi_order")
    if not isinstance(pi_order, list) or not all(isinstance(x, str) for x in pi_order):
        state.issue("ERROR", "BAD_PI_ORDER", "pi_order must be a string array", case_id=case_id, path=gt_path)
        pi_order = []
    elif list(pi_order) != list(primary_inputs):
        state.issue(
            "ERROR", "GT_PI_ORDER_MISMATCH",
            "ground-truth pi_order must exactly match the manifest PI order",
            case_id=case_id, path=gt_path,
        )
    po_order = gt.get("po_order")
    if not isinstance(po_order, list) or not all(isinstance(x, str) for x in po_order):
        state.issue("ERROR", "BAD_PO_ORDER", "po_order must be a string array", case_id=case_id, path=gt_path)
    elif list(po_order) != list(primary_outputs):
        state.issue(
            "ERROR", "GT_PO_ORDER_MISMATCH",
            "ground-truth po_order must exactly match the manifest PO order",
            case_id=case_id, path=gt_path,
        )

    order = gt.get("instance_order")
    if not isinstance(order, list) or not all(isinstance(x, str) for x in order):
        state.issue("ERROR", "BAD_INSTANCE_ORDER", "instance_order must be a string array", case_id=case_id, path=gt_path)
        order = list(ids)
    elif len(order) != len(set(order)) or set(order) != set(ids):
        state.issue(
            "ERROR", "GT_INSTANCE_ORDER_MISMATCH",
            "instance_order must contain every manifest instance exactly once",
            case_id=case_id, path=gt_path,
        )

    patterns = gt.get("patterns")
    if not isinstance(patterns, list):
        state.issue("ERROR", "BAD_PATTERNS", "patterns must be an array", case_id=case_id, path=gt_path)
        patterns = []
    declared_count = gt.get("pattern_count")
    if declared_count != len(patterns):
        state.issue(
            "ERROR", "PATTERN_COUNT_MISMATCH",
            f"pattern_count={declared_count!r}, actual patterns={len(patterns)}",
            case_id=case_id, path=gt_path,
        )

    seen_bits: dict[str, int] = {}
    pattern_masks: Counter[str] = Counter()
    singleton_instances: set[str] = set()
    po_set = set(primary_outputs)
    width = len(order)
    for index, pattern in enumerate(patterns):
        if not isinstance(pattern, Mapping):
            state.issue("ERROR", "BAD_PATTERN", f"patterns[{index}] is not an object", case_id=case_id, path=gt_path)
            continue
        bits = pattern.get("pattern_bits")
        if not isinstance(bits, str) or not BITS_RE.fullmatch(bits):
            state.issue("ERROR", "BAD_PATTERN_BITS", f"patterns[{index}].pattern_bits must be a binary string", case_id=case_id, path=gt_path)
            continue
        if len(bits) != len(pi_order):
            state.issue(
                "ERROR", "PATTERN_LENGTH_MISMATCH",
                f"patterns[{index}] has {len(bits)} bits, expected {len(pi_order)}",
                case_id=case_id, path=gt_path,
            )
        if bits in seen_bits:
            state.issue(
                "ERROR", "DUPLICATE_PATTERN",
                f"patterns[{index}] duplicates patterns[{seen_bits[bits]}]",
                case_id=case_id, path=gt_path,
            )
        else:
            seen_bits[bits] = index

        mask = parse_mask(pattern.get("activation_mask"), width)
        if mask is None:
            state.issue(
                "ERROR", "BAD_ACTIVATION_MASK",
                f"patterns[{index}].activation_mask must be a width-{width} binary string",
                case_id=case_id, path=gt_path,
            )
            continue
        mask_value = pattern.get("activation_mask_value")
        if not isinstance(mask_value, int) or mask_value != int(mask, 2):
            state.issue(
                "ERROR", "MASK_VALUE_MISMATCH",
                f"patterns[{index}].activation_mask_value does not equal int(activation_mask, 2)",
                case_id=case_id, path=gt_path,
            )

        active_instances = pattern.get("active_instances")
        expected_active = [str(order[pos]) for pos, bit in enumerate(mask) if bit == "1"]
        if not isinstance(active_instances, list) or active_instances != expected_active:
            state.issue(
                "ERROR", "ACTIVE_INSTANCES_MISMATCH",
                f"patterns[{index}].active_instances must equal {expected_active!r}",
                case_id=case_id, path=gt_path,
            )

        mismatches = pattern.get("mismatched_outputs")
        if not isinstance(mismatches, list) or not mismatches or not all(isinstance(x, str) for x in mismatches):
            state.issue(
                "ERROR", "NO_OBSERVABLE_MISMATCH",
                f"patterns[{index}] must contain at least one mismatched_outputs entry",
                case_id=case_id, path=gt_path,
            )
            mismatches = []
        elif len(mismatches) != len(set(mismatches)):
            state.issue("ERROR", "DUPLICATE_MISMATCH_OUTPUT", f"patterns[{index}] repeats a mismatched output", case_id=case_id, path=gt_path)
        unknown_outputs = sorted(set(mismatches) - po_set)
        if unknown_outputs:
            state.issue(
                "ERROR", "UNKNOWN_MISMATCH_OUTPUT",
                f"patterns[{index}] references non-PO outputs: {unknown_outputs}",
                case_id=case_id, path=gt_path,
            )
        output = pattern.get("output")
        if mismatches and output != mismatches[0]:
            state.issue(
                "ERROR", "LEGACY_OUTPUT_MISMATCH",
                f"patterns[{index}].output must equal the first mismatched_outputs entry",
                case_id=case_id, path=gt_path,
            )

        sample_class = pattern.get("sample_class")
        if not isinstance(sample_class, str) or not sample_class:
            state.issue("ERROR", "MISSING_SAMPLE_CLASS", f"patterns[{index}].sample_class is required", case_id=case_id, path=gt_path)
        active_count = mask.count("1")
        if sample_class == "singleton" and active_count != 1:
            state.issue("ERROR", "SAMPLE_CLASS_MISMATCH", f"patterns[{index}] is singleton but has {active_count} active instances", case_id=case_id, path=gt_path)
        if sample_class == "pair" and active_count != 2:
            state.issue("ERROR", "SAMPLE_CLASS_MISMATCH", f"patterns[{index}] is pair but has {active_count} active instances", case_id=case_id, path=gt_path)
        if sample_class in ("all", "all_on") and active_count != width:
            state.issue("ERROR", "SAMPLE_CLASS_MISMATCH", f"patterns[{index}] is all-on but has {active_count}/{width} active instances", case_id=case_id, path=gt_path)

        requested = parse_mask(pattern.get("requested_mask"), width)
        if requested is None:
            state.issue("ERROR", "BAD_REQUESTED_MASK", f"patterns[{index}].requested_mask is missing or invalid", case_id=case_id, path=gt_path)
        elif requested != mask:
            state.issue(
                "ERROR", "REQUESTED_MASK_MISMATCH",
                f"patterns[{index}] requested {requested}, solver returned activation mask {mask}",
                case_id=case_id, path=gt_path,
            )

        if active_count == 1 and mismatches:
            singleton_instances.add(expected_active[0])
        pattern_masks[mask] += 1
        stats["patterns"] += 1
        stats[f"mask_popcount_{active_count}"] += 1

    for missing in sorted(set(ids) - singleton_instances):
        state.issue(
            "ERROR", "MISSING_SINGLETON_WITNESS",
            f"no unique, observable singleton witness was found for {missing}",
            case_id=case_id, path=gt_path,
        )
    stats["unique_patterns"] = len(seen_bits)
    stats["singleton_instances_covered"] = len(singleton_instances)

    mask_results = gt.get("mask_results")
    if not isinstance(mask_results, list):
        state.issue("ERROR", "BAD_MASK_RESULTS", "mask_results must be an array", case_id=case_id, path=gt_path)
    else:
        seen_result_masks: set[str] = set()
        for index, result in enumerate(mask_results):
            if not isinstance(result, Mapping):
                state.issue("ERROR", "BAD_MASK_RESULT", f"mask_results[{index}] is not an object", case_id=case_id, path=gt_path)
                continue
            status = result.get("status")
            if status not in ("sat", "unsat", "unknown", "timeout"):
                state.issue("ERROR", "BAD_MASK_STATUS", f"mask_results[{index}].status={status!r} is invalid", case_id=case_id, path=gt_path)
            requested = parse_mask(
                get_first(result, ("requested_mask", "activation_mask", "mask")), width
            )
            if requested is None:
                state.issue(
                    "ERROR", "BAD_MASK_RESULT_MASK",
                    f"mask_results[{index}] has no valid width-{width} requested mask",
                    case_id=case_id, path=gt_path,
                )
                continue
            if requested in seen_result_masks:
                state.issue(
                    "ERROR", "DUPLICATE_MASK_RESULT",
                    f"mask_results repeats requested mask {requested}",
                    case_id=case_id, path=gt_path,
                )
            seen_result_masks.add(requested)
            if status == "sat" and pattern_masks[requested] == 0:
                state.issue(
                    "ERROR", "SAT_MASK_WITHOUT_PATTERN",
                    f"mask {requested} is marked sat but has no stored witness",
                    case_id=case_id, path=gt_path,
                )
            if status in ("unsat", "unknown", "timeout") and pattern_masks[requested] > 0:
                state.issue(
                    "ERROR", "NON_SAT_MASK_WITH_PATTERN",
                    f"mask {requested} is marked {status} but has {pattern_masks[requested]} stored witness(es)",
                    case_id=case_id, path=gt_path,
                )
            witness_count = result.get("witness_count")
            if isinstance(witness_count, int) and witness_count != pattern_masks[requested]:
                state.issue(
                    "ERROR", "MASK_WITNESS_COUNT_MISMATCH",
                    f"mask {requested}: witness_count={witness_count}, stored={pattern_masks[requested]}",
                    case_id=case_id, path=gt_path,
                )

    if profile_rule is not None:
        expected_masks = requested_groundtruth_masks(width)
        expected_mask_set = set(expected_masks)
        result_by_mask: dict[str, Mapping[str, Any]] = {}
        if isinstance(mask_results, list):
            for result in mask_results:
                if not isinstance(result, Mapping):
                    continue
                requested = parse_mask(
                    get_first(result, ("requested_mask", "activation_mask", "mask")),
                    width,
                )
                if requested is not None and requested not in result_by_mask:
                    result_by_mask[requested] = result

        actual_mask_set = set(result_by_mask)
        if actual_mask_set != expected_mask_set:
            state.issue(
                "ERROR",
                "GT_PROFILE_MASK_SET_MISMATCH",
                f"profile {profile_rule.profile_id!r} requires exact masks "
                f"{expected_masks}; missing={sorted(expected_mask_set - actual_mask_set)}, "
                f"extra={sorted(actual_mask_set - expected_mask_set)}",
                case_id=case_id,
                path=gt_path,
            )

        solver = gt.get("solver")
        expected_solver_values = {
            "witnesses_per_mask": profile_rule.witnesses_per_mask,
            "witnesses_per_singleton": profile_rule.witnesses_per_singleton,
            "witnesses_per_pair": profile_rule.witnesses_per_pair,
            "witnesses_per_all": profile_rule.witnesses_per_all,
        }
        if not isinstance(solver, Mapping):
            state.issue(
                "ERROR", "GT_PROFILE_SOLVER_MISSING",
                f"profile {profile_rule.profile_id!r} requires solver configuration metadata",
                case_id=case_id, path=gt_path,
            )
        else:
            for field_name, expected_value in expected_solver_values.items():
                actual_value = solver.get(field_name)
                if expected_value is None:
                    matches = field_name not in solver
                else:
                    matches = actual_value == expected_value
                if not matches:
                    state.issue(
                        "ERROR", "GT_PROFILE_SOLVER_MISMATCH",
                        f"profile {profile_rule.profile_id!r} requires solver.{field_name}="
                        f"{expected_value!r}, got {actual_value!r}",
                        case_id=case_id, path=gt_path,
                    )

        expected_pattern_count = 0
        for mask in expected_masks:
            target = groundtruth_witness_target(profile_rule, mask)
            expected_pattern_count += target
            result = result_by_mask.get(mask)
            if result is None:
                continue
            if result.get("status") != "sat":
                state.issue(
                    "ERROR", "GT_PROFILE_MASK_NOT_SAT",
                    f"profile {profile_rule.profile_id!r} requires mask {mask} status='sat', "
                    f"got {result.get('status')!r}",
                    case_id=case_id, path=gt_path,
                )
            if result.get("requested_witnesses") != target:
                state.issue(
                    "ERROR", "GT_PROFILE_REQUESTED_WITNESSES_MISMATCH",
                    f"profile {profile_rule.profile_id!r} requires mask {mask} "
                    f"requested_witnesses={target}, got {result.get('requested_witnesses')!r}",
                    case_id=case_id, path=gt_path,
                )
            if result.get("witness_count") != target or pattern_masks[mask] != target:
                state.issue(
                    "ERROR", "GT_PROFILE_WITNESS_COUNT_MISMATCH",
                    f"profile {profile_rule.profile_id!r} requires mask {mask} {target} "
                    f"witnesses; mask_results={result.get('witness_count')!r}, "
                    f"stored={pattern_masks[mask]}",
                    case_id=case_id, path=gt_path,
                )
        if len(patterns) != expected_pattern_count or gt.get("pattern_count") != expected_pattern_count:
            state.issue(
                "ERROR", "GT_PROFILE_PATTERN_COUNT_MISMATCH",
                f"profile {profile_rule.profile_id!r} requires {expected_pattern_count} "
                f"positive patterns, got stored={len(patterns)}, declared={gt.get('pattern_count')!r}",
                case_id=case_id, path=gt_path,
            )

    trigger_consistency = gt.get("trigger_consistency")
    if not isinstance(trigger_consistency, list):
        state.issue(
            "ERROR", "BAD_TRIGGER_CONSISTENCY",
            "trigger_consistency must be an array with one check per instance",
            case_id=case_id, path=gt_path,
        )
    else:
        consistency_by_id: dict[str, str] = {}
        for item in trigger_consistency:
            if isinstance(item, Mapping) and isinstance(item.get("instance_id"), str):
                consistency_by_id[item["instance_id"]] = str(item.get("status"))
        for expected_id in ids:
            status = consistency_by_id.get(expected_id)
            if status not in ("equivalent", "literal_only"):
                state.issue(
                    "ERROR", "TRIGGER_CONSISTENCY_NOT_PROVEN",
                    f"{expected_id} trigger consistency status is {status!r}",
                    case_id=case_id, path=gt_path,
                )
    return dict(stats)


def validate_negative_patterns(
    negative: Mapping[str, Any],
    negative_path: Path,
    case_manifest: Mapping[str, Any],
    case_id: str,
    benchmark: str,
    primary_inputs: Sequence[str],
    instances: Sequence[Mapping[str, Any]],
    ids: Sequence[str],
    positive_bits: set[str],
    minimum_count: int,
    expected_count: int | None,
    profile_id: str | None,
    state: ValidationState,
) -> dict[str, int]:
    stats = Counter[str]()
    if negative.get("schema_version") != NEGATIVE_SCHEMA:
        state.issue(
            "ERROR", "BAD_NEGATIVE_SCHEMA",
            f"expected negative schema {NEGATIVE_SCHEMA!r}, got {negative.get('schema_version')!r}",
            case_id=case_id, path=negative_path,
        )
    if negative.get("case_id") != case_id:
        state.issue(
            "ERROR", "NEGATIVE_CASE_ID_MISMATCH",
            f"negative case_id={negative.get('case_id')!r}, expected {case_id!r}",
            case_id=case_id, path=negative_path,
        )
    if negative.get("benchmark") != benchmark:
        state.issue(
            "ERROR", "NEGATIVE_BENCHMARK_MISMATCH",
            f"negative benchmark={negative.get('benchmark')!r}, expected {benchmark!r}",
            case_id=case_id, path=negative_path,
        )

    golden_relative = get_first(
        case_manifest, ("golden_path", "golden_file", "golden")
    )
    combined_relative = get_first(
        case_manifest, ("combined_path", "trojaned_path", "trojan_file", "combined")
    )
    if negative.get("origin_path") != golden_relative:
        state.issue(
            "ERROR", "NEGATIVE_ORIGIN_PATH_MISMATCH",
            f"negative origin_path={negative.get('origin_path')!r}, manifest={golden_relative!r}",
            case_id=case_id, path=negative_path,
        )
    if negative.get("trojan_path") != combined_relative:
        state.issue(
            "ERROR", "NEGATIVE_TROJAN_PATH_MISMATCH",
            f"negative trojan_path={negative.get('trojan_path')!r}, manifest={combined_relative!r}",
            case_id=case_id, path=negative_path,
        )
    files = case_manifest.get("files")
    normalized_files = (
        {normalize_relpath(str(key)): value for key, value in files.items()}
        if isinstance(files, Mapping)
        else {}
    )
    for artifact_field, relative in (
        ("origin_sha256", golden_relative),
        ("trojan_sha256", combined_relative),
    ):
        manifest_hash = None
        if isinstance(relative, str):
            metadata = normalized_files.get(normalize_relpath(relative))
            if isinstance(metadata, Mapping):
                manifest_hash = metadata.get("sha256")
        artifact_hash = negative.get(artifact_field)
        if artifact_hash is not None and artifact_hash != manifest_hash:
            state.issue(
                "ERROR", "NEGATIVE_CIRCUIT_HASH_MISMATCH",
                f"negative {artifact_field}={artifact_hash!r}, manifest={manifest_hash!r}",
                case_id=case_id, path=negative_path,
            )

    pi_order = negative.get("pi_order")
    if not isinstance(pi_order, list) or not all(isinstance(item, str) for item in pi_order):
        state.issue("ERROR", "BAD_NEGATIVE_PI_ORDER", "negative pi_order must be a string array", case_id=case_id, path=negative_path)
        pi_order = []
    elif list(pi_order) != list(primary_inputs):
        state.issue(
            "ERROR", "NEGATIVE_PI_ORDER_MISMATCH",
            "negative pi_order must exactly match the manifest PI order",
            case_id=case_id, path=negative_path,
        )
    order = negative.get("instance_order")
    if not isinstance(order, list) or list(order) != list(ids):
        state.issue(
            "ERROR", "NEGATIVE_INSTANCE_ORDER_MISMATCH",
            "negative instance_order must exactly match manifest instances[]",
            case_id=case_id, path=negative_path,
        )

    patterns = negative.get("patterns")
    if not isinstance(patterns, list):
        state.issue("ERROR", "BAD_NEGATIVE_PATTERNS", "negative patterns must be an array", case_id=case_id, path=negative_path)
        patterns = []
    declared_count = negative.get("pattern_count")
    if declared_count != len(patterns):
        state.issue(
            "ERROR", "NEGATIVE_PATTERN_COUNT_MISMATCH",
            f"negative pattern_count={declared_count!r}, actual={len(patterns)}",
            case_id=case_id, path=negative_path,
        )
    if len(patterns) < minimum_count:
        state.issue(
            "ERROR", "INSUFFICIENT_HARD_NEGATIVES",
            f"hard-negative count {len(patterns)} is below required minimum {minimum_count}",
            case_id=case_id, path=negative_path,
        )
    if expected_count is not None and len(patterns) != expected_count:
        state.issue(
            "ERROR", "HARD_NEGATIVE_PROFILE_COUNT_MISMATCH",
            f"profile {profile_id!r} requires exactly {expected_count} hard negatives, "
            f"got {len(patterns)}",
            case_id=case_id, path=negative_path,
        )

    generation = negative.get("generation")
    if not isinstance(generation, Mapping):
        state.issue("ERROR", "BAD_NEGATIVE_GENERATION", "negative generation{} is required", case_id=case_id, path=negative_path)
    else:
        generated = generation.get("generated")
        requested = generation.get("requested")
        if generated != len(patterns):
            state.issue(
                "ERROR", "NEGATIVE_GENERATED_COUNT_MISMATCH",
                f"generation.generated={generated!r}, stored={len(patterns)}",
                case_id=case_id, path=negative_path,
            )
        if not isinstance(requested, int) or isinstance(requested, bool) or requested < 0:
            state.issue("ERROR", "BAD_NEGATIVE_REQUEST_COUNT", "generation.requested must be a non-negative integer", case_id=case_id, path=negative_path)
        elif len(patterns) < requested or generation.get("complete") is not True:
            state.issue(
                "ERROR", "INCOMPLETE_HARD_NEGATIVES",
                f"requested {requested}, generated {len(patterns)}, complete={generation.get('complete')!r}",
                case_id=case_id, path=negative_path,
            )
        if expected_count is not None:
            for field_name, actual_value in (
                ("requested", requested),
                ("generated", generated),
            ):
                if actual_value != expected_count:
                    state.issue(
                        "ERROR", "HARD_NEGATIVE_PROFILE_GENERATION_MISMATCH",
                        f"profile {profile_id!r} requires generation.{field_name}="
                        f"{expected_count}, got {actual_value!r}",
                        case_id=case_id, path=negative_path,
                    )

    zero_mask = "0" * len(ids)
    pi_positions = {name: position for position, name in enumerate(pi_order)}
    seen = set(positive_bits)
    id_to_instance = {
        instance_id(instance): instance for instance in instances if instance_id(instance)
    }
    for index, pattern in enumerate(patterns):
        if not isinstance(pattern, Mapping):
            state.issue("ERROR", "BAD_NEGATIVE_PATTERN", f"negative patterns[{index}] is not an object", case_id=case_id, path=negative_path)
            continue
        bits = pattern.get("pattern_bits")
        if not isinstance(bits, str) or not BITS_RE.fullmatch(bits):
            state.issue("ERROR", "BAD_NEGATIVE_PATTERN_BITS", f"negative patterns[{index}].pattern_bits must be binary", case_id=case_id, path=negative_path)
            continue
        if len(bits) != len(pi_order):
            state.issue(
                "ERROR", "NEGATIVE_PATTERN_LENGTH_MISMATCH",
                f"negative patterns[{index}] has {len(bits)} bits, expected {len(pi_order)}",
                case_id=case_id, path=negative_path,
            )
        if bits in seen:
            state.issue(
                "ERROR", "DUPLICATE_POSITIVE_NEGATIVE_PATTERN",
                f"negative patterns[{index}] duplicates a positive or earlier negative pattern",
                case_id=case_id, path=negative_path,
            )
        seen.add(bits)

        mask = parse_mask(pattern.get("activation_mask"), len(ids))
        requested_mask = parse_mask(pattern.get("requested_mask"), len(ids))
        if mask != zero_mask or requested_mask != zero_mask:
            state.issue(
                "ERROR", "NEGATIVE_NONZERO_MASK",
                f"negative patterns[{index}] must have all-zero activation/requested masks",
                case_id=case_id, path=negative_path,
            )
        if pattern.get("activation_mask_value") != 0:
            state.issue("ERROR", "NEGATIVE_MASK_VALUE", f"negative patterns[{index}].activation_mask_value must be 0", case_id=case_id, path=negative_path)
        if pattern.get("active_instances") != []:
            state.issue("ERROR", "NEGATIVE_ACTIVE_INSTANCES", f"negative patterns[{index}].active_instances must be empty", case_id=case_id, path=negative_path)
        if pattern.get("mismatched_outputs") != []:
            state.issue("ERROR", "NEGATIVE_HAS_MISMATCH", f"negative patterns[{index}].mismatched_outputs must be empty", case_id=case_id, path=negative_path)
        if pattern.get("sample_class") != "near_miss":
            state.issue("ERROR", "BAD_NEGATIVE_SAMPLE_CLASS", f"negative patterns[{index}].sample_class must be 'near_miss'", case_id=case_id, path=negative_path)
        if "simulated_equal" in pattern and pattern.get("simulated_equal") is not True:
            state.issue("ERROR", "NEGATIVE_NOT_SIMULATED_EQUAL", f"negative patterns[{index}].simulated_equal must be true", case_id=case_id, path=negative_path)
        if "label" in pattern and pattern.get("label") != 0:
            state.issue("ERROR", "BAD_NEGATIVE_LABEL", f"negative patterns[{index}].label must be 0", case_id=case_id, path=negative_path)

        near_id = pattern.get("near_instance")
        target = id_to_instance.get(near_id) if isinstance(near_id, str) else None
        if target is None:
            state.issue("ERROR", "BAD_NEAR_INSTANCE", f"negative patterns[{index}].near_instance is invalid", case_id=case_id, path=negative_path)

        inactive_ids: set[str] = set()
        target_unsatisfied: list[Mapping[str, Any]] = []
        for current in instances:
            current_id = instance_id(current)
            trigger = current.get("trigger")
            literals = trigger.get("literals") if isinstance(trigger, Mapping) else []
            unsatisfied: list[Mapping[str, Any]] = []
            for literal in literals if isinstance(literals, list) else []:
                if not isinstance(literal, Mapping):
                    continue
                net = literal.get("net")
                position = pi_positions.get(net) if isinstance(net, str) else None
                if position is None or position >= len(bits):
                    state.issue(
                        "ERROR", "NEGATIVE_NON_PI_TRIGGER",
                        f"negative validation cannot resolve trigger literal {net!r} as a PI",
                        case_id=case_id, path=negative_path,
                    )
                    unsatisfied.append(literal)
                elif int(bits[position]) != literal.get("required_value"):
                    unsatisfied.append(literal)
            if unsatisfied:
                inactive_ids.add(current_id)
            if current_id == near_id:
                target_unsatisfied = unsatisfied
        if inactive_ids != set(ids):
            state.issue(
                "ERROR", "NEGATIVE_TRIGGER_ACTIVE",
                f"negative patterns[{index}] leaves active instances {sorted(set(ids) - inactive_ids)}",
                case_id=case_id, path=negative_path,
            )
        if target is not None and len(target_unsatisfied) != 1:
            state.issue(
                "ERROR", "NOT_EXACT_NEAR_MISS",
                f"negative patterns[{index}] violates {len(target_unsatisfied)} literals of {near_id}; expected exactly one",
                case_id=case_id, path=negative_path,
            )
        flipped = pattern.get("flipped_literal")
        if target_unsatisfied and isinstance(flipped, Mapping):
            expected_literal = target_unsatisfied[0]
            if (
                flipped.get("net") != expected_literal.get("net")
                or flipped.get("required_value") != expected_literal.get("required_value")
            ):
                state.issue(
                    "ERROR", "FLIPPED_LITERAL_MISMATCH",
                    f"negative patterns[{index}].flipped_literal does not identify the unique failed literal",
                    case_id=case_id, path=negative_path,
                )
        elif not isinstance(flipped, Mapping):
            state.issue("ERROR", "MISSING_FLIPPED_LITERAL", f"negative patterns[{index}].flipped_literal is required", case_id=case_id, path=negative_path)
        stats["hard_negatives"] += 1
    stats["unique_hard_negatives"] = max(0, len(seen) - len(positive_bits))
    return dict(stats)


def validate_case(
    record: CaseRecord,
    gt_index: Mapping[str, list[tuple[Path, dict[str, Any]]]],
    negative_index: Mapping[str, list[tuple[Path, dict[str, Any]]]],
    state: ValidationState,
    skip_hash: bool,
    allow_missing_groundtruth: bool,
    minimum_hard_negatives: int,
    profile_rules: Mapping[str, GroundtruthProfileRule],
    profile_by_matrix_cell: Mapping[tuple[Any, ...], str],
    matrix_configured: bool,
) -> dict[str, Any]:
    case = record.data
    case_id_value = get_first(case, ("case_id", "id", "name"))
    case_id = str(case_id_value) if case_id_value is not None else ""
    if not case_id:
        case_id = f"<missing:{record.source}>"
        state.issue("ERROR", "MISSING_CASE_ID", "case_id is required", path=record.source)
    if case.get("schema_version") != CASE_SCHEMA:
        state.issue(
            "ERROR", "BAD_CASE_SCHEMA",
            f"expected case schema {CASE_SCHEMA!r}, got {case.get('schema_version')!r}",
            case_id=case_id, path=record.source,
        )
    benchmark = infer_benchmark(record, case)
    instances = canonical_instances(case)

    index_data = record.index_data
    if index_data is not None:
        state.counters["index_entries"] += 1
        if index_data.get("schema_version") != "v4-multi-trojan-dataset-index/1":
            state.issue(
                "ERROR", "BAD_INDEX_SCHEMA",
                f"unexpected dataset index schema {index_data.get('schema_version')!r}",
                case_id=case_id, path=record.source,
            )
        for field_name, expected_value in (("case_id", case_id), ("benchmark", benchmark)):
            if index_data.get(field_name) != expected_value:
                state.issue(
                    "ERROR", "INDEX_METADATA_MISMATCH",
                    f"index {field_name}={index_data.get(field_name)!r}, manifest={expected_value!r}",
                    case_id=case_id, path=record.source,
                )
        expected_size = index_data.get("case_manifest_size_bytes")
        if not isinstance(expected_size, int) or expected_size != record.source.stat().st_size:
            state.issue(
                "ERROR", "INDEX_MANIFEST_SIZE_MISMATCH",
                f"index case_manifest_size_bytes={expected_size!r}, actual={record.source.stat().st_size}",
                case_id=case_id, path=record.source,
            )
        expected_hash = index_data.get("case_manifest_sha256")
        if not isinstance(expected_hash, str) or not SHA256_RE.fullmatch(expected_hash.lower()):
            state.issue(
                "ERROR", "BAD_INDEX_MANIFEST_SHA256",
                "index case_manifest_sha256 is missing or invalid",
                case_id=case_id, path=record.source,
            )
        elif not skip_hash and sha256_file(record.source) != expected_hash.lower():
            state.issue(
                "ERROR", "INDEX_MANIFEST_SHA256_MISMATCH",
                "case manifest content does not match the aggregate index hash",
                case_id=case_id, path=record.source,
            )
        indexed_generation = index_data.get("generation")
        manifest_generation = case.get("generation")
        if isinstance(indexed_generation, Mapping) and isinstance(manifest_generation, Mapping):
            pairs = (
                ("trojan_count", "trojan_count"),
                ("trigger_size", "trigger_size"),
                ("trigger_topology", "trigger_topology"),
                ("seed", "seed"),
                ("source_golden_sha256", "source_golden_sha256"),
            )
            for index_key, manifest_key in pairs:
                indexed_value = indexed_generation.get(index_key)
                manifest_value = manifest_generation.get(manifest_key)
                if indexed_value != manifest_value:
                    state.issue(
                        "ERROR", "INDEX_GENERATION_MISMATCH",
                        f"index generation.{index_key}={indexed_value!r}, manifest={manifest_value!r}",
                        case_id=case_id, path=record.source,
                    )
            indexed_placement = indexed_generation.get("victim_placement")
            manifest_placement_record = manifest_generation.get("payload_placement")
            manifest_placement = (
                manifest_placement_record.get("requested")
                if isinstance(manifest_placement_record, Mapping)
                else None
            )
            if indexed_placement != manifest_placement:
                state.issue(
                    "ERROR", "INDEX_GENERATION_MISMATCH",
                    f"index generation.victim_placement={indexed_placement!r}, manifest={manifest_placement!r}",
                    case_id=case_id, path=record.source,
                )

    expected_paths: list[tuple[str, Any]] = [
        ("golden", get_first(case, ("golden_path", "golden_file", "golden"))),
        ("combined", get_first(case, ("combined_path", "trojaned_path", "trojan_file", "combined"))),
    ]
    for index, item in enumerate(instances):
        expected_paths.append(
            (
                f"individual[{instance_id(item) or index}]",
                get_first(item, ("individual_path", "trojan_path", "file")),
            )
        )
    paths = check_file_table(record, case_id, expected_paths, state, skip_hash)
    primary_inputs, primary_outputs = validate_interfaces(case, paths, state, case_id)
    ids, victims = validate_instances(case, instances, state, case_id)
    validate_trigger_witnesses(
        case, instances, ids, primary_inputs, state, case_id
    )

    generation = case.get("generation") if isinstance(case.get("generation"), Mapping) else {}
    trigger_topology = generation.get(
        "trigger_topology",
        generation.get("topology", generation.get("interaction_topology", "disjoint")),
    )
    if trigger_topology not in ("disjoint", "shared_trigger_literals"):
        state.issue(
            "ERROR", "BAD_TRIGGER_TOPOLOGY",
            f"unsupported generation trigger topology: {trigger_topology!r}",
            case_id=case_id,
        )
    placement = generation.get("payload_placement")
    if not isinstance(placement, Mapping):
        state.issue("ERROR", "MISSING_PAYLOAD_PLACEMENT", "generation.payload_placement is required", case_id=case_id)
    elif placement.get("fallback_used") is True:
        state.issue(
            "WARNING", "PAYLOAD_PLACEMENT_FALLBACK",
            f"victim placement used a relaxed fallback: {placement.get('fallback_reason')}",
            case_id=case_id, strict_error=True,
        )

    victim_placement = placement.get("requested") if isinstance(placement, Mapping) else None
    matrix_cell = (
        benchmark,
        generation.get("trojan_count", len(instances)),
        generation.get("trigger_size"),
        trigger_topology,
        generation.get("seed"),
        victim_placement,
    )
    matrix_profile_id = profile_by_matrix_cell.get(matrix_cell)
    indexed_profile_id = (
        index_data.get("groundtruth_profile")
        if isinstance(index_data, Mapping)
        else None
    )
    if (
        isinstance(indexed_profile_id, str)
        and matrix_profile_id is not None
        and indexed_profile_id != matrix_profile_id
    ):
        state.issue(
            "ERROR", "INDEX_GROUNDTRUTH_PROFILE_MISMATCH",
            f"index groundtruth_profile={indexed_profile_id!r}, matrix={matrix_profile_id!r}",
            case_id=case_id, path=record.source,
        )
    profile_id = matrix_profile_id or (
        indexed_profile_id if isinstance(indexed_profile_id, str) else None
    )
    profile_rule = profile_rules.get(profile_id) if profile_id is not None else None
    if matrix_configured and profile_id is None:
        state.issue(
            "ERROR", "MISSING_GROUNDTRUTH_PROFILE",
            "case cannot be mapped to a matrix ground-truth profile",
            case_id=case_id, path=record.source,
        )
    elif profile_id is not None and profile_rule is None:
        state.issue(
            "ERROR", "UNKNOWN_GROUNDTRUTH_PROFILE",
            f"ground-truth profile {profile_id!r} is not defined by the matrix",
            case_id=case_id, path=record.source,
        )

    gt_path = find_groundtruth_candidate(record)
    gt_value: dict[str, Any] | None = None
    indexed = gt_index.get(case_id, [])
    if len(indexed) > 1:
        state.issue(
            "ERROR", "DUPLICATE_GROUNDTRUTH",
            f"multiple ground-truth files claim case_id {case_id}: {[str(item[0]) for item in indexed]}",
            case_id=case_id,
        )
    elif len(indexed) == 1:
        gt_path, gt_value = indexed[0]
    elif gt_path is not None:
        try:
            loaded = read_json(gt_path)
            if isinstance(loaded, dict):
                gt_value = loaded
            else:
                state.issue("ERROR", "BAD_GROUNDTRUTH_ROOT", "ground truth root is not an object", case_id=case_id, path=gt_path)
        except (OSError, json.JSONDecodeError) as error:
            state.issue("ERROR", "GT_JSON_PARSE", str(error), case_id=case_id, path=gt_path)

    gt_stats: dict[str, int] = {}
    if gt_value is None or gt_path is None:
        state.issue(
            "WARNING" if allow_missing_groundtruth else "ERROR",
            "MISSING_GROUNDTRUTH",
            "no ground-truth JSON was found for the case",
            case_id=case_id,
            path=record.source,
        )
    else:
        state.counters["groundtruth_files"] += 1
        gt_stats = validate_groundtruth(
            gt_value,
            gt_path,
            case,
            case_id,
            benchmark,
            primary_inputs,
            primary_outputs,
            ids,
            profile_rule,
            state,
        )
        state.counters.update(gt_stats)

    positive_bits: set[str] = set()
    if isinstance(gt_value, Mapping) and isinstance(gt_value.get("patterns"), list):
        positive_bits = {
            item.get("pattern_bits")
            for item in gt_value["patterns"]
            if isinstance(item, Mapping) and isinstance(item.get("pattern_bits"), str)
        }

    negative_path = find_negative_candidate(record)
    negative_value: dict[str, Any] | None = None
    indexed_negatives = negative_index.get(case_id, [])
    if len(indexed_negatives) > 1:
        state.issue(
            "ERROR", "DUPLICATE_NEGATIVE_ARTIFACT",
            f"multiple negative-pattern files claim case_id {case_id}: {[str(item[0]) for item in indexed_negatives]}",
            case_id=case_id,
        )
    elif len(indexed_negatives) == 1:
        negative_path, negative_value = indexed_negatives[0]
    elif negative_path is not None:
        try:
            loaded = read_json(negative_path)
            if isinstance(loaded, dict):
                negative_value = loaded
            else:
                state.issue("ERROR", "BAD_NEGATIVE_ROOT", "negative-pattern root is not an object", case_id=case_id, path=negative_path)
        except (OSError, json.JSONDecodeError) as error:
            state.issue("ERROR", "NEGATIVE_JSON_PARSE", str(error), case_id=case_id, path=negative_path)

    negative_stats: dict[str, int] = {}
    if negative_value is None or negative_path is None:
        required_negative_count = max(
            minimum_hard_negatives,
            profile_rule.hard_negatives if profile_rule is not None else 0,
        )
        if required_negative_count > 0:
            state.issue(
                "ERROR", "MISSING_NEGATIVE_PATTERNS",
                f"no negative_patterns.json found; required count is {required_negative_count}",
                case_id=case_id, path=record.source,
            )
    else:
        state.counters["negative_pattern_files"] += 1
        negative_stats = validate_negative_patterns(
            negative_value,
            negative_path,
            case,
            case_id,
            benchmark,
            primary_inputs,
            instances,
            ids,
            positive_bits,
            minimum_hard_negatives,
            profile_rule.hard_negatives if profile_rule is not None else None,
            profile_rule.profile_id if profile_rule is not None else None,
            state,
        )
        state.counters.update(negative_stats)

    row = {
        "case_id": case_id,
        "benchmark": benchmark,
        "seed": generation.get("seed"),
        "trojan_count": generation.get("trojan_count", len(instances)),
        "trigger_size": generation.get("trigger_size"),
        "trigger_topology": trigger_topology,
        "payload_topology": generation.get("payload_topology"),
        "payload_cone_overlap": generation.get("payload_cone_overlap"),
        "payload_fallback_used": (
            placement.get("fallback_used") if isinstance(placement, Mapping) else None
        ),
        "victim_placement": (
            placement.get("requested") if isinstance(placement, Mapping) else None
        ),
        "victim_placement_strategy": (
            placement.get("actual_strategy") if isinstance(placement, Mapping) else None
        ),
        "phase_id": index_data.get("phase_id") if index_data else None,
        "split": index_data.get("split") if index_data else None,
        "groundtruth_profile": profile_id,
        "size_class": index_data.get("size_class") if index_data else None,
        "matrix_run_status": index_data.get("matrix_run_status") if index_data else None,
        "instance_count": len(instances),
        "distinct_victim_count": len(set(victims)),
        "pi_count": len(primary_inputs),
        "po_count": len(primary_outputs),
        "pattern_count": gt_stats.get("patterns", 0),
        "hard_negative_count": negative_stats.get("hard_negatives", 0),
        "singleton_instances_covered": gt_stats.get("singleton_instances_covered", 0),
        "manifest": str(record.source),
        "groundtruth": str(gt_path) if gt_path is not None else None,
        "negative_patterns": str(negative_path) if negative_path is not None else None,
        "source_golden_sha256": generation.get("source_golden_sha256"),
        "trigger_overlap": generation.get("trigger_overlap"),
    }
    state.counters["cases"] += 1
    state.counters["instances"] += len(instances)
    state.by_benchmark[benchmark]["cases"] += 1
    state.by_benchmark[benchmark]["instances"] += len(instances)
    state.by_benchmark[benchmark]["patterns"] += gt_stats.get("patterns", 0)
    state.by_benchmark[benchmark]["hard_negatives"] += negative_stats.get("hard_negatives", 0)
    return row


def seed_values(value: Any) -> list[int]:
    if isinstance(value, list) and all(isinstance(item, int) for item in value):
        return list(value)
    if isinstance(value, Mapping):
        start, count = value.get("start"), value.get("count")
        if isinstance(start, int) and isinstance(count, int) and count >= 0:
            return list(range(start, start + count))
    return []


def parse_groundtruth_profiles(
    matrix: Mapping[str, Any], state: ValidationState
) -> dict[str, GroundtruthProfileRule]:
    raw_profiles = matrix.get("groundtruth_profiles")
    if not isinstance(raw_profiles, Mapping):
        state.issue("ERROR", "BAD_GROUNDTRUTH_PROFILES", "matrix groundtruth_profiles must be an object")
        return {}

    result: dict[str, GroundtruthProfileRule] = {}
    for raw_id, raw_profile in raw_profiles.items():
        profile_id = str(raw_id)
        if not isinstance(raw_profile, Mapping):
            state.issue("ERROR", "BAD_GROUNDTRUTH_PROFILE", f"groundtruth_profiles.{profile_id} must be an object")
            continue

        per_mask = get_first(
            raw_profile,
            ("witnesses_per_requested_mask", "witnesses_per_mask"),
        )
        if per_mask is None:
            per_mask = raw_profile.get("pair_witnesses_per_pair")
        hard_negatives = raw_profile.get("hard_negatives_per_case", 0)
        raw_values = {
            "witnesses_per_mask": per_mask,
            "hard_negatives": hard_negatives,
            "witnesses_per_singleton": raw_profile.get("singleton_witnesses_per_instance"),
            "witnesses_per_pair": raw_profile.get("pair_witnesses_per_pair"),
            "witnesses_per_all": raw_profile.get("all_on_witnesses_per_case"),
        }
        invalid = False
        for field_name, value in raw_values.items():
            if value is None and field_name.startswith("witnesses_per_") and field_name != "witnesses_per_mask":
                continue
            minimum = 0 if field_name == "hard_negatives" else 1
            if not isinstance(value, int) or isinstance(value, bool) or value < minimum:
                state.issue(
                    "ERROR", "BAD_GROUNDTRUTH_PROFILE_VALUE",
                    f"groundtruth_profiles.{profile_id}.{field_name} must be an integer >= {minimum}",
                )
                invalid = True
        if invalid:
            continue
        result[profile_id] = GroundtruthProfileRule(
            profile_id=profile_id,
            witnesses_per_mask=int(per_mask),
            hard_negatives=int(hard_negatives),
            witnesses_per_singleton=raw_values["witnesses_per_singleton"],
            witnesses_per_pair=raw_values["witnesses_per_pair"],
            witnesses_per_all=raw_values["witnesses_per_all"],
        )
    return result


def matrix_keys(
    matrix: Mapping[str, Any], state: ValidationState
) -> tuple[set[tuple[Any, ...]], dict[str, Any], dict[tuple[Any, ...], str]]:
    expected: set[tuple[Any, ...]] = set()
    profile_by_cell: dict[tuple[Any, ...], str] = {}
    details: dict[str, Any] = {"phases": [], "enabled_expected_case_count": 0}
    phases = matrix.get("phases")
    if not isinstance(phases, list):
        state.issue("ERROR", "BAD_MATRIX_PHASES", "matrix phases must be an array")
        return expected, details, profile_by_cell
    seed_owners: dict[int, str] = {}
    heldout_circuits: set[str] = set()
    nonheldout_circuits: set[str] = set()
    defaults = matrix.get("defaults") if isinstance(matrix.get("defaults"), Mapping) else {}
    default_placement = defaults.get("victim_placement", "random")
    for index, phase in enumerate(phases):
        if not isinstance(phase, Mapping):
            state.issue("ERROR", "BAD_MATRIX_PHASE", f"phases[{index}] is not an object")
            continue
        phase_id = str(phase.get("id", f"phase-{index}"))
        enabled = phase.get("enabled", True) is True
        circuits = phase.get("circuits") if isinstance(phase.get("circuits"), list) else []
        counts = phase.get("trojan_counts") if isinstance(phase.get("trojan_counts"), list) else []
        sizes = phase.get("trigger_sizes") if isinstance(phase.get("trigger_sizes"), list) else []
        topologies = phase.get("trigger_topologies")
        if not isinstance(topologies, list):
            topologies = phase.get("topologies")
        if not isinstance(topologies, list):
            # Compatibility with the initial matrix draft.
            topologies = phase.get("interaction_classes")
        if not isinstance(topologies, list):
            topologies = ["disjoint"]
        seeds = seed_values(phase.get("seeds"))
        victim_placement = phase.get("victim_placement", default_placement)
        groundtruth_profile = phase.get("groundtruth_profile")
        if not isinstance(groundtruth_profile, str) or not groundtruth_profile:
            state.issue(
                "ERROR", "MISSING_PHASE_GROUNDTRUTH_PROFILE",
                f"phase {phase_id}: groundtruth_profile is required",
            )
        if victim_placement not in ("random", "output-near"):
            state.issue(
                "ERROR", "BAD_MATRIX_VICTIM_PLACEMENT",
                f"phase {phase_id}: victim_placement must be random or output-near",
            )
        calculated = len(circuits) * len(counts) * len(sizes) * len(topologies) * len(seeds)
        declared = phase.get("expected_case_count")
        if declared != calculated:
            state.issue(
                "ERROR", "MATRIX_COUNT_MISMATCH",
                f"phase {phase_id}: expected_case_count={declared!r}, Cartesian product={calculated}",
            )
        split = phase.get("split")
        if split == "heldout_ood":
            heldout_circuits.update(str(item) for item in circuits)
        elif enabled:
            nonheldout_circuits.update(str(item) for item in circuits)
        if enabled:
            for seed in seeds:
                owner = seed_owners.get(seed)
                if owner is not None:
                    state.issue(
                        "ERROR", "MATRIX_SEED_REUSE",
                        f"seed {seed} is reused by enabled phases {owner} and {phase_id}",
                    )
                seed_owners[seed] = phase_id
            for circuit in circuits:
                for count in counts:
                    for size in sizes:
                        for topology in topologies:
                            for seed in seeds:
                                cell = (
                                    str(circuit), count, size, topology, seed,
                                    victim_placement,
                                )
                                expected.add(cell)
                                if isinstance(groundtruth_profile, str):
                                    profile_by_cell[cell] = groundtruth_profile
            details["enabled_expected_case_count"] += calculated
        details["phases"].append(
            {
                "id": phase_id,
                "split": split,
                "enabled": enabled,
                "calculated_case_count": calculated,
            }
        )
    overlap = sorted(heldout_circuits & nonheldout_circuits)
    if overlap:
        state.issue(
            "ERROR", "HELDOUT_CIRCUIT_LEAKAGE",
            f"heldout_ood circuits also appear in an enabled non-heldout phase: {overlap}",
        )
    return expected, details, profile_by_cell


def validate_matrix(
    matrix_path: Path,
    repo_root: Path,
    state: ValidationState,
) -> tuple[
    set[tuple[Any, ...]],
    dict[str, Any],
    dict[str, GroundtruthProfileRule],
    dict[tuple[Any, ...], str],
]:
    try:
        matrix = read_json(matrix_path)
    except (OSError, json.JSONDecodeError) as error:
        state.issue("ERROR", "MATRIX_JSON_PARSE", str(error), path=matrix_path)
        return set(), {}, {}, {}
    if not isinstance(matrix, dict):
        state.issue("ERROR", "BAD_MATRIX_ROOT", "matrix root must be an object", path=matrix_path)
        return set(), {}, {}, {}
    profile_rules = parse_groundtruth_profiles(matrix, state)
    catalog = matrix.get("benchmark_catalog")
    if not isinstance(catalog, Mapping):
        state.issue("ERROR", "BAD_BENCHMARK_CATALOG", "benchmark_catalog must be an object", path=matrix_path)
        catalog = {}
    for name, metadata in catalog.items():
        if not isinstance(metadata, Mapping):
            state.issue("ERROR", "BAD_BENCHMARK_METADATA", f"benchmark_catalog.{name} must be an object", path=matrix_path)
            continue
        raw_path = metadata.get("path")
        if not isinstance(raw_path, str):
            state.issue("ERROR", "MISSING_BENCHMARK_PATH", f"benchmark_catalog.{name}.path is required", path=matrix_path)
            continue
        path = (repo_root / raw_path).resolve()
        if not path.is_file():
            state.issue("ERROR", "BENCHMARK_NOT_FOUND", f"benchmark {name} not found", path=path)
            continue
        expected_hash = metadata.get("sha256")
        if not isinstance(expected_hash, str) or not SHA256_RE.fullmatch(expected_hash.lower()):
            state.issue("ERROR", "BAD_BENCHMARK_SHA256", f"benchmark_catalog.{name}.sha256 is invalid", path=matrix_path)
        elif sha256_file(path) != expected_hash.lower():
            state.issue("ERROR", "BENCHMARK_SHA256_MISMATCH", f"benchmark {name} content changed", path=path)
        parsed_inputs, parsed_outputs = parse_bench_interfaces(path)
        if metadata.get("primary_inputs") != len(parsed_inputs):
            state.issue("ERROR", "BENCHMARK_PI_COUNT_MISMATCH", f"benchmark {name} PI count changed", path=path)
        if metadata.get("primary_outputs") != len(parsed_outputs):
            state.issue("ERROR", "BENCHMARK_PO_COUNT_MISMATCH", f"benchmark {name} PO count changed", path=path)
        assignment_count = count_bench_assignments(path)
        if metadata.get("gate_assignments") != assignment_count:
            state.issue(
                "ERROR", "BENCHMARK_GATE_COUNT_MISMATCH",
                f"benchmark {name} gate-assignment count changed",
                path=path,
            )
    expected, details, profile_by_cell = matrix_keys(matrix, state)
    for profile_id in sorted(set(profile_by_cell.values()) - set(profile_rules)):
        state.issue(
            "ERROR", "UNDEFINED_PHASE_GROUNDTRUTH_PROFILE",
            f"enabled phase references undefined ground-truth profile {profile_id!r}",
            path=matrix_path,
        )
    details["path"] = str(matrix_path)
    details["benchmark_count"] = len(catalog)
    details["groundtruth_profiles"] = {
        profile_id: asdict(rule) for profile_id, rule in sorted(profile_rules.items())
    }
    return expected, details, profile_rules, profile_by_cell


def compare_dataset_to_matrix(
    rows: Sequence[Mapping[str, Any]],
    expected: set[tuple[Any, ...]],
    require_complete: bool,
    state: ValidationState,
) -> dict[str, int]:
    actual_counts: Counter[tuple[Any, ...]] = Counter()
    for row in rows:
        key = (
            row.get("benchmark"),
            row.get("trojan_count"),
            row.get("trigger_size"),
            row.get("trigger_topology", "disjoint"),
            row.get("seed"),
            row.get("victim_placement"),
        )
        actual_counts[key] += 1
        if key not in expected:
            state.issue(
                "WARNING", "CASE_OUTSIDE_MATRIX",
                f"case dimensions are not in the configured matrix: {key}",
                case_id=str(row.get("case_id")), strict_error=True,
            )
    for key, count in actual_counts.items():
        if count > 1:
            state.issue("ERROR", "DUPLICATE_MATRIX_CELL", f"matrix cell {key} has {count} cases; expected one")
    missing = expected - set(actual_counts)
    if require_complete:
        for key in sorted(missing, key=str):
            state.issue("ERROR", "MISSING_MATRIX_CASE", f"missing required matrix cell: {key}")
    return {
        "expected_cells": len(expected),
        "present_expected_cells": len(set(actual_counts) & expected),
        "missing_expected_cells": len(missing),
        "outside_matrix_cases": sum(count for key, count in actual_counts.items() if key not in expected),
    }


