    parser.add_argument("--negative-root", type=Path, help="optional separate root containing v4-hard-negatives-1 JSON files")
    parser.add_argument("--matrix", type=Path, help="experiment matrix JSON to validate")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--summary-json", type=Path, help="write a machine-readable validation summary")
    parser.add_argument("--summary-markdown", type=Path, help="write a Markdown validation summary")
    parser.add_argument(
        "--ready-index", type=Path,
        help="atomically write JSONL rows for cases with no case-level validation errors",
    )
    parser.add_argument(
        "--rejected-index", type=Path,
        help="atomically write JSONL rows for rejected cases with exact validation reasons",
    )
    parser.add_argument("--skip-hash", action="store_true", help="validate hash syntax but do not read file contents")
