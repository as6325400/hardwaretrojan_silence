def grouped_case_summary(
    rows: Sequence[Mapping[str, Any]], fields: Sequence[str]
) -> dict[str, dict[str, dict[str, int]]]:
    result: dict[str, dict[str, dict[str, int]]] = {}
    for field_name in fields:
        groups: dict[str, Counter[str]] = defaultdict(Counter)
        for row in rows:
            key = str(row.get(field_name))
            groups[key]["cases"] += 1
            groups[key]["instances"] += int(row.get("instance_count") or 0)
            groups[key]["patterns"] += int(row.get("pattern_count") or 0)
            groups[key]["hard_negatives"] += int(row.get("hard_negative_count") or 0)
            groups[key]["singleton_instances_covered"] += int(
                row.get("singleton_instances_covered") or 0
            )
        result[field_name] = {
            key: dict(sorted(values.items())) for key, values in sorted(groups.items())
        }
    return result


def build_acceptance_summary(
    rows: Sequence[Mapping[str, Any]], issues: Sequence[Issue]
) -> tuple[dict[str, Any], set[str], dict[str, list[Issue]]]:
    errors_by_case: dict[str, list[Issue]] = defaultdict(list)
    for issue in issues:
        if issue.severity == "ERROR" and issue.case_id is not None:
            errors_by_case[issue.case_id].append(issue)

    ready_ids = {
        str(row.get("case_id"))
        for row in rows
        if str(row.get("case_id")) not in errors_by_case
    }
    result: dict[str, Any] = {
        "scheduled_cases": len(rows),
        "gt_ready_cases": len(ready_ids),
        "rejected_cases": len(rows) - len(ready_ids),
    }

    dimensions = (
        "phase_id",
        "benchmark",
        "trojan_count",
        "trigger_topology",
        "groundtruth_profile",
    )
    by_dimension: dict[str, dict[str, dict[str, int]]] = {}
    for field_name in dimensions:
        groups: dict[str, Counter[str]] = defaultdict(Counter)
        for row in rows:
            case_id = str(row.get("case_id"))
            group = groups[str(row.get(field_name))]
            group["scheduled"] += 1
            status_key = "gt_ready" if case_id in ready_ids else "rejected"
            group[status_key] += 1
            group[f"{status_key}_positive_patterns"] += int(row.get("pattern_count") or 0)
            group[f"{status_key}_hard_negatives"] += int(row.get("hard_negative_count") or 0)
        by_dimension[field_name] = {
            key: dict(sorted(values.items())) for key, values in sorted(groups.items())
        }
    result["by_dimension"] = by_dimension
    result["gt_ready_positive_patterns"] = sum(
        int(row.get("pattern_count") or 0)
        for row in rows
        if str(row.get("case_id")) in ready_ids
    )
    result["gt_ready_hard_negatives"] = sum(
        int(row.get("hard_negative_count") or 0)
        for row in rows
        if str(row.get("case_id")) in ready_ids
    )
    result["rejected_artifact_positive_patterns"] = sum(
        int(row.get("pattern_count") or 0)
        for row in rows
        if str(row.get("case_id")) not in ready_ids
    )
    result["rejected_artifact_hard_negatives"] = sum(
        int(row.get("hard_negative_count") or 0)
        for row in rows
        if str(row.get("case_id")) not in ready_ids
    )
    return result, ready_ids, errors_by_case


def relative_or_absolute(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return str(path.resolve())


def indexed_artifact(path_value: Any, root: Path) -> dict[str, Any] | None:
    if not isinstance(path_value, str):
        return None
    path = Path(path_value)
    if not path.is_file():
        return None
    return {
        "path": relative_or_absolute(path, root),
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
    }


def write_jsonl_atomic(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True, separators=(",", ":")))
            handle.write("\n")
    temporary.replace(path)


def write_acceptance_indexes(
    ready_path: Path,
    rejected_path: Path,
    rows: Sequence[Mapping[str, Any]],
    ready_ids: set[str],
    errors_by_case: Mapping[str, Sequence[Issue]],
    dataset_root: Path,
    summary_path: Path | None,
) -> None:
    ready_rows: list[dict[str, Any]] = []
    rejected_rows: list[dict[str, Any]] = []
    summary_reference = (
        relative_or_absolute(summary_path, dataset_root) if summary_path is not None else None
    )
    for row in sorted(rows, key=lambda item: str(item.get("case_id"))):
        case_id = str(row.get("case_id"))
        artifacts: dict[str, Any] = {}
        for label, field_name in (
            ("case_manifest", "manifest"),
            ("groundtruth", "groundtruth"),
            ("negative_patterns", "negative_patterns"),
        ):
            metadata = indexed_artifact(row.get(field_name), dataset_root)
            if metadata is not None:
                artifacts[label] = metadata["path"]
                artifacts[f"{label}_sha256"] = metadata["sha256"]
                artifacts[f"{label}_size_bytes"] = metadata["size_bytes"]

        base = {
            "artifacts": artifacts,
            "benchmark": row.get("benchmark"),
            "case_id": case_id,
            "generation": {
                "seed": row.get("seed"),
                "source_golden_sha256": row.get("source_golden_sha256"),
                "trigger_overlap": row.get("trigger_overlap"),
                "trigger_size": row.get("trigger_size"),
                "trigger_topology": row.get("trigger_topology"),
                "trojan_count": row.get("trojan_count"),
                "victim_placement": row.get("victim_placement"),
            },
            "groundtruth_profile": row.get("groundtruth_profile"),
            "phase_id": row.get("phase_id"),
            "split": row.get("split"),
            "validation": {
                "hard_negative_count": row.get("hard_negative_count"),
                "instance_count": row.get("instance_count"),
                "positive_pattern_count": row.get("pattern_count"),
                "singleton_instances_covered": row.get("singleton_instances_covered"),
                "summary": summary_reference,
            },
        }
        if case_id in ready_ids:
            base.update(
                {
                    "schema_version": "v4-gt-ready-case-index/1",
                    "status": "gt_ready",
                }
            )
            ready_rows.append(base)
        else:
            failures = [asdict(issue) for issue in errors_by_case.get(case_id, [])]
            base.update(
                {
                    "failure_category": "groundtruth_validation_failure"
                    if any(
                        issue["code"].startswith(("GT_", "INCOMPLETE_GROUNDTRUTH", "MISSING_SINGLETON"))
                        for issue in failures
                    )
                    else "dataset_validation_failure",
                    "failures": failures,
                    "schema_version": "v4-rejected-case-index/1",
                    "status": "rejected",
                }
            )
            rejected_rows.append(base)
    write_jsonl_atomic(ready_path, ready_rows)
    write_jsonl_atomic(rejected_path, rejected_rows)


